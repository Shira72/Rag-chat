def format_sources(sources: list[tuple[str, str, str, str]]) -> str:
    """sources: רשימה של (מזהה, שם המסמך, תווית מהדורה, טקסט)."""
    blocks = []
    for sid, doc_name, edition, text in sources:
        blocks.append(f'<source id="{sid}" document="{doc_name}" edition="{edition}">\n{text}\n</source>')
    return "\n\n".join(blocks)


def answer_user_message(question: str, sources_block: str) -> str:
    return f"המקורות:\n\n{sources_block}\n\nהשאלה: {question}"


